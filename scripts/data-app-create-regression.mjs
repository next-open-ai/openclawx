function setup(file, services = {}, props = {}) {
  const { descriptor } = parse(readFileSync(new URL(`../apps/renderer/src/features/data/${file}`, import.meta.url), 'utf8'));
  const code = ts.transpileModule(compileScript(descriptor, { id: 'create-regression' }).content, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
  const exports = {};
  const mounted = [], unmounted = [];
  const importer = id => {
    if (id === 'vue') return { ...vue, onMounted: fn => mounted.push(fn), onUnmounted: fn => unmounted.push(fn), onBeforeUnmount: fn => unmounted.push(fn) };
    if (id === '../../services/api' || id === '../../services/live-data') return services;
    if (id === './workbench-presentation') return { appPresentation: () => ({ canShare: false }) };
    if (id === '@openclawx/contracts') return { dataObjectAnnotationsSchema: { parse: () => ({ description: '' }) } };
    return {};
  };
  vm.runInNewContext(code, { exports, require: importer, Error, crypto: { randomUUID }, window: { navigator: {} }, document: { activeElement: null } });
  const events = [];
  const state = exports.default.setup(file === 'DataWorkbenchPage.vue' ? { employeeId: 'general', ...props } : props, { expose: () => {}, emit: (...args) => events.push(args) });
  return { state, events, mount: async () => { for (const fn of mounted) await fn(); }, unmount: () => { for (const fn of unmounted) fn(); } };
}
