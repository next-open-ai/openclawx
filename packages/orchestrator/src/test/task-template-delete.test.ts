import assert from 'node:assert/strict';
import test from 'node:test';
import {randomUUID} from 'node:crypto';
import {TaskTemplateDeleteSchema} from '@workmate/contracts';
import {TemplateTaskService} from '../template-tasks.js';
import {MemoryStore} from '../storage/memory.js';
import {businessSummaryTemplate} from '../task-skills/business-summary/index.js';

test('TP-T19: owner/revision guarded template deletion removes choices but preserves existing tasks and results',async()=>{
  const store=new MemoryStore(),service=new TemplateTaskService(store),owner={orgId:'org',userId:'user'};
  const {id:_id,version:_version,...configuration}=businessSummaryTemplate;
  const parameters={period:'2026-09',rows:[{name:'测试业务',revenue:100,cost:60}]};
  let record=await service.saveDefinition(owner,{...configuration,defaults:parameters});
  await service.trial(owner,record.id,record.revision);
  record=await service.publish(owner,record.id,record.revision);
  const input={name:'保留的任务',templateId:record.id,templateVersion:record.draft.version,parameters:{}};
  const task=await service.save(owner,input);
  const run=await service.run(owner,task.id,randomUUID());
  const history=await service.detail(owner,task.id);
  assert.equal(TaskTemplateDeleteSchema.safeParse({revision:0}).success,false);
  assert.equal(TaskTemplateDeleteSchema.safeParse({revision:1,all:true}).success,false);
  await assert.rejects(service.deleteDefinition({...owner,userId:'other'},record.id,record.revision),/不存在/);
  await assert.rejects(service.deleteDefinition(owner,record.id,record.revision+1),error=>(error as {statusCode:number}).statusCode===409);
  assert.equal((await service.definitions(owner)).length,1);
  await service.deleteDefinition(owner,record.id,record.revision);
  assert.equal((await service.definitions(owner)).length,0);
  assert.equal((await service.listTemplates(owner)).some(item=>item.id===record.id),false);
  await assert.rejects(service.definition(owner,record.id),/已删除/);
  await assert.rejects(service.save(owner,input),/已删除/);
  await assert.rejects(service.saveDefinition(owner,configuration,record.id,record.revision),/已删除/);
  await assert.rejects(service.archive(owner,record.id,record.revision,false),/已删除/);
  await assert.rejects(service.deleteDefinition(owner,record.id,record.revision),/已删除/);
  assert.deepEqual(await service.detail(owner,task.id),history);
  assert.equal((await service.result(owner,task.id,run.id)).id,run.result!.id);
  const edited=await service.save(owner,{...input,name:'修改已有任务'},task.id,task.revision);
  assert.equal((await service.run(owner,edited.id,randomUUID())).status,'completed');
  const at=Date.now()+60_000;
  await service.updateSchedule(owner,edited.id,{revision:edited.revision,schedule:{kind:'once',at,enabled:true}});
  await service.tickScheduled(at);
  assert.equal((await service.detail(owner,task.id)).runs.filter(item=>item.trigger==='scheduled'&&item.status==='completed').length,1);
  assert.ok((await store.keys('task-template-definitions:')).length===1);
});
