 assert.deepEqual(await parameterSkillOptions(store,{orgId:'org',userId:'bob'}),{skills:[]});
 assert.equal((await parameterSkillOptions(store,{orgId:'org',userId:'legacy-user'})).skills[0].id,'legacy');
